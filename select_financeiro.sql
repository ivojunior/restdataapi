FROM SE2070 E2
INNER JOIN SA2070 A2 ON A2.D_E_L_E_T_ = ' ' AND A2.A2_FILIAL = '  ' AND A2.A2_COD = E2.E2_FORNECE AND A2.A2_LOJA = E2.E2_LOJA
LEFT JOIN PA6000 A6 ON A6.D_E_L_E_T_ = ' ' AND A6.PA6_FILIAL = '  ' AND A6.PA6_COD = E2.E2_YOPER 
