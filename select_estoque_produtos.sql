SELECT B2.B2_FILIAL, B2.B2_LOCAL, B2.B2_COD, B1.B1_DESC, (B2.B2_QATU/B1.B1_CONV) QTDE, B2.B2_VATU1
FROM SB2070 B2
INNER JOIN SB1000 B1 ON B1.D_E_L_E_T_ = ' ' AND B1.B1_FILIAL = '  ' AND B1.B1_COD = B2.B2_COD AND B1.B1_TIPO = 'PA'
WHERE B2.D_E_L_E_T_ = ' ' AND B2.B2_QATU > 0 AND B2.B2_LOCAL = '01'
ORDER BY B2.B2_FILIAL, B2.B2_COD

